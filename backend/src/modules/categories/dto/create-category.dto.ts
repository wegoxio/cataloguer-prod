import {
  IsBoolean,
  IsEnum,
  IsInt,
  IsNotEmpty,
  IsOptional,
  IsString,
  MaxLength,
  Min,
  MinLength,
  IsUUID,
} from 'class-validator';
import { CategoryKind } from '../entities/category.entity';

/**
 * The global pipe runs with `whitelist` + `forbidNonWhitelisted`, so EVERY
 * property needs a decorator — an undecorated one is treated as unknown and
 * the whole request 400s. That is not theoretical: it is exactly how the
 * Phase 2 value endpoint became unreachable from HTTP while its service tests
 * all passed.
 */
export class CreateCategoryDto {
  @IsString()
  @IsNotEmpty()
  name!: string;

  // Generated by the system from the name; user input is ignored
  @IsString()
  @IsOptional()
  slug?: string;

  @IsString()
  @IsOptional()
  description?: string;

  @IsString()
  @MaxLength(160)
  @IsOptional()
  metaTitle?: string;

  @IsString()
  @MaxLength(300)
  @IsOptional()
  metaDescription?: string;

  @IsUUID()
  @IsOptional()
  parentCategoryId?: string;

  // ---------- Phase 4: presentation metadata ----------

  @IsEnum(CategoryKind)
  @IsOptional()
  kind?: CategoryKind;

  /** Storefront display name. Blank is refused: absence means "use `name`". */
  @IsString()
  @MinLength(1)
  @MaxLength(160)
  @IsOptional()
  publicLabel?: string;

  @IsInt()
  @Min(0)
  @IsOptional()
  sortOrder?: number;

  @IsBoolean()
  @IsOptional()
  showInNavigation?: boolean;

}
