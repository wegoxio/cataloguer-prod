import { Type } from 'class-transformer';
import {
  IsArray,
  IsDefined,
  IsNotEmpty,
  IsOptional,
  IsString,
  MaxLength,
  IsUUID,
  IsEnum,
  IsNumber,
  Min,
  IsInt,
  IsBoolean,
  ValidateNested,
} from 'class-validator';
import { ProductStatus } from '../catalogue/product-status.enum';
import { ProductSaleMode } from '../catalogue/product-sale-mode.enum';

/** One field answered at creation time (B4a3). */
export class CreationFieldValueDto {
  @IsUUID()
  definitionId!: string;

  /**
   * Deliberately untyped here: whether this must be a string, a decimal
   * string or a boolean is the field definition's decision, and the service
   * writer enforces it in the one place that knows the type.
   */
  @IsDefined()
  value!: unknown;
}

export class StorePriceDto {
  @IsUUID()
  storeId!: string;

  @IsNumber()
  @Min(0)
  price!: number;

  @IsNumber()
  @Min(0)
  @IsOptional()
  salePrice?: number;
}

export class CreateProductDto {
  @IsString()
  @IsNotEmpty()
  name!: string;

  // Generated by the system from the name; user input is ignored
  @IsString()
  @IsOptional()
  slug?: string;

  @IsString()
  @IsOptional()
  description?: string;

  @IsString()
  @MaxLength(160)
  @IsOptional()
  metaTitle?: string;

  @IsString()
  @MaxLength(300)
  @IsOptional()
  metaDescription?: string;

  @IsString()
  @IsOptional()
  sku?: string;

  /**
   * The supplier's reference (governing decision 18). Separate from `sku`,
   * never unique, and never derived from it. Blank clears it.
   */
  @IsString()
  @MaxLength(255)
  @IsOptional()
  manufacturerCode?: string;

  @IsEnum(ProductStatus)
  @IsOptional()
  status?: ProductStatus;

  @IsEnum(ProductSaleMode)
  @IsOptional()
  saleMode?: ProductSaleMode;

  @IsUUID()
  @IsOptional()
  categoryId?: string;

  /** Every category the item is reachable through. Supersedes categoryId. */
  @IsArray()
  @IsUUID('4', { each: true })
  @IsOptional()
  categoryIds?: string[];

  @IsString()
  @IsOptional()
  optionLabel?: string;

  @IsArray()
  @IsUUID('4', { each: true })
  @IsOptional()
  storeIds?: string[];

  @IsArray()
  @ValidateNested({ each: true })
  @Type(() => StorePriceDto)
  @IsOptional()
  storePrices?: StorePriceDto[];

  /**
   * Field values the product is born with (B4a3), written inside the creation
   * transaction so required-field validation sees them. Creation-only: after
   * this, values change through the field-value endpoints.
   */
  @IsArray()
  @ValidateNested({ each: true })
  @Type(() => CreationFieldValueDto)
  @IsOptional()
  fieldValues?: CreationFieldValueDto[];

  @IsNumber()
  @Min(0)
  @IsOptional()
  price?: number;

  @IsNumber()
  @Min(0)
  @IsOptional()
  salePrice?: number;

  @IsNumber()
  @Min(0)
  @IsOptional()
  cost?: number;

  @IsInt()
  @Min(0)
  @IsOptional()
  stockQuantity?: number;

  @IsBoolean()
  @IsOptional()
  trackInventory?: boolean;
}
